window.applyReminderFix = function(index) {
  const rem = state.activeReminders[index];
  if (rem && typeof rem.fixAction === "function") {
    const remId = rem.id;
    rem.fixAction();
    state.totalSavedKwh += 0.15; // Log behavioral nudge contribution
    syncToBackend("/api/reminders/fix", { reminderId: remId });
    evaluateRules();
    renderAll();
  }
};

