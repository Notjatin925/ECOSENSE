// --- Web Audio API Chimes ---
function playChime(type = "nudge") {
  if (!state.soundEnabled) return;
  try {
    const AudioContext = window.AudioContext || window.webkitAudioContext;
    if (!state.audioCtx) {
      state.audioCtx = new AudioContext();
    }
    if (state.audioCtx.state === "suspended") {
      state.audioCtx.resume();
    }
    const ctx = state.audioCtx;
    const now = ctx.currentTime;
    const osc = ctx.createOscillator();
    const gain = ctx.createGain();
    
    osc.connect(gain);
    gain.connect(ctx.destination);

    if (type === "critical") {
      // Rapid alert double-beep
      osc.type = "sawtooth";
      osc.frequency.setValueAtTime(660, now);
      osc.frequency.setValueAtTime(880, now + 0.12);
      gain.gain.setValueAtTime(0.08, now);
      gain.gain.exponentialRampToValueAtTime(0.001, now + 0.35);
      osc.start(now);
      osc.stop(now + 0.35);
    } else {
      // Gentle environmental marimba-like chime
      osc.type = "sine";
      osc.frequency.setValueAtTime(523.25, now); // C5
      osc.frequency.setValueAtTime(659.25, now + 0.1); // E5
      gain.gain.setValueAtTime(0.12, now);
      gain.gain.exponentialRampToValueAtTime(0.001, now + 0.45);
      osc.start(now);
      osc.stop(now + 0.45);
    }
  } catch (e) {
    // Audio context not allowed until user gesture, graceful fallback
  }
}

// --- Helper Functions ---
function formatSimTime(minutesTotal) {
  const normalized = ((minutesTotal % 1440) + 1440) % 1440;
  const hours = Math.floor(normalized / 60);
  const mins = Math.floor(normalized % 60);
  const period = hours >= 12 ? "PM" : "AM";
  const displayHours = hours % 12 === 0 ? 12 : hours % 12;
  const formattedMins = mins < 10 ? "0" + mins : mins;
  return `${displayHours}:${formattedMins} ${period}`;
}

function isPeakTariff(minutesTotal) {
  const norm = ((minutesTotal % 1440) + 1440) % 1440;
  // Peak tariff: 18:00 (6 PM) to 22:00 (10 PM)
  return norm >= 18 * 60 && norm <= 22 * 60;
}

function calculateACWatts(temp) {
  // AC power draw increases sharply at low temperatures
  // 26C: ~700W, 24C: ~900W, 20C: ~1250W, 18C: ~1550W
  if (temp <= 18) return 1550;
  if (temp === 19) return 1400;
  if (temp === 20) return 1250;
  if (temp === 21) return 1150;
  if (temp === 22) return 1050;
  if (temp === 23) return 970;
  if (temp === 24) return 890;
  if (temp === 25) return 780;
  return 680;
}

// --- Rule Engine for Reminders ---
function evaluateRules() {
  const reminders = [];
  const rooms = state.rooms;
  const inPeak = isPeakTariff(state.simMinutes);

  // RULE 1: Unoccupied Room Energy Waste (Living Room)
  if (!rooms.livingRoom.occupied && rooms.livingRoom.vacantMinutes >= 5) {
    const fanOn = rooms.livingRoom.appliances.fan.status === "on";
    const lightOn = rooms.livingRoom.appliances.lights.status === "on";
    if (fanOn || lightOn) {
      reminders.push({
        id: "vacant_living_room",
        severity: "critical",
        title: "Living Room Vacant — Lights/Fan Running",
        desc: `Living Room has been empty for ${rooms.livingRoom.vacantMinutes} mins, but appliances are still active drawing ${(fanOn ? 75 : 0) + (lightOn ? 30 : 0)}W.`,
        ecoFact: "Lighting and unneeded fans in empty rooms account for ~12% of avoidable residential electricity waste.",
        impact: "Save ~105W & 0.48 kg CO2",
        actionText: "Turn Off Room",
        fixAction: () => {
          rooms.livingRoom.appliances.fan.status = "off";
          rooms.livingRoom.appliances.lights.status = "off";
          updateApplianceWattages();
          showToast("🌿 Living Room turned off. Saved ~105 Watts!");
        }
      });
    }
  }

  // RULE 2: Air Conditioner Sub-Optimal Temperature
  if (rooms.bedroom.appliances.ac.status === "on") {
    if (rooms.bedroom.acTemp < 24) {
      const diff = 24 - rooms.bedroom.acTemp;
      const energyWastePercent = diff * 6; // ~6% extra energy per degree C below 24
      reminders.push({
        id: "ac_temp_nudge",
        severity: "warning",
        title: `AC Set to ${rooms.bedroom.acTemp}°C (Eco-Optimum is 24°C)`,
        desc: `Operating at ${rooms.bedroom.acTemp}°C consumes ~${energyWastePercent}% more power than recommended by the Bureau of Energy Efficiency (BEE).`,
        ecoFact: "Every 1°C increase in AC setting reduces compressor load by 6%, saving roughly 4-9 units of electricity monthly per household.",
        impact: `Save ~${(calculateACWatts(rooms.bedroom.acTemp) - calculateACWatts(24))}W & 2.1 kg CO2/wk`,
        actionText: "Set to 24°C",
        fixAction: () => {
          rooms.bedroom.acTemp = 24;
          updateApplianceWattages();
          showToast("❄️ AC optimized to 24°C eco-standard! Energy saved.");
        }
      });
    }

    // RULE 3: AC On With Window Open
    if (rooms.bedroom.windowOpen) {
      reminders.push({
        id: "ac_window_open",
        severity: "critical",
        title: "Thermal Leak: Bedroom Window Is Open While AC Runs",
        desc: "Hot outdoor air entering forces compressor into maximum load, doubling cooling losses.",
        ecoFact: "Cooling an unsealed room increases AC duty cycle by over 45%, rapidly spiking carbon emissions.",
        impact: "Save ~400W & avoid motor strain",
        actionText: "Close Window",
        fixAction: () => {
          rooms.bedroom.windowOpen = false;
          showToast("🪟 Bedroom window closed. Thermal efficiency restored.");
        }
      });
    }
  }

  // RULE 4: Water Geyser Continuous Overrun
  if (rooms.bathroom.appliances.geyser.status === "on" && rooms.bathroom.geyserMinutes >= 20) {
    reminders.push({
      id: "geyser_overrun",
      severity: "critical",
      title: "Geyser Overheating (Running > 20 Mins)",
      desc: `Water heater has been active for ${rooms.bathroom.geyserMinutes} mins. 2000W element is cyclically heating already-hot water.`,
      ecoFact: "Water heaters are the single highest wattage appliance in most homes (2-3 kW). Running past 15-20 mins wastes pure thermal energy.",
      impact: "Save 2000W & 1.64 kg CO2/hr",
      actionText: "Turn Off Geyser",
      fixAction: () => {
        rooms.bathroom.appliances.geyser.status = "off";
        rooms.bathroom.geyserMinutes = 0;
        updateApplianceWattages();
        showToast("🚿 Geyser shut off. Prevented 2000W waste.");
      }
    });
  }

  // RULE 5: High Phantom / Vampire Standby Loads
  const phantomApps = [];
  let phantomWatts = 0;
  if (rooms.livingRoom.appliances.tv.status === "standby") {
    phantomApps.push("Smart TV");
    phantomWatts += rooms.livingRoom.appliances.tv.standbyWatts;
  }
  if (rooms.livingRoom.appliances.console.status === "standby") {
    phantomApps.push("Console");
    phantomWatts += rooms.livingRoom.appliances.console.standbyWatts;
  }
  if (rooms.bedroom.appliances.laptop.status === "standby") {
    phantomApps.push("Laptop Charger");
    phantomWatts += rooms.bedroom.appliances.laptop.standbyWatts;
  }
  if (rooms.kitchen.appliances.microwave.status === "standby") {
    phantomApps.push("Microwave");
    phantomWatts += rooms.kitchen.appliances.microwave.standbyWatts;
  }

  if (phantomWatts >= 20) {
    reminders.push({
      id: "phantom_vampire_load",
      severity: "warning",
      title: `Vampire / Phantom Load Alert (${phantomWatts}W Idle)`,
      desc: `${phantomApps.join(", ")} are in standby mode, drawing electricity silently without providing active benefit.`,
      ecoFact: "Phantom power accounts for 5% to 10% of total residential electricity consumption globally, wasting millions of tons of coal annually.",
      impact: `Save ${phantomWatts}W & 0.75 kg CO2/wk`,
      actionText: "Cut Standby Loads",
      fixAction: () => {
        rooms.livingRoom.appliances.tv.status = "off";
        rooms.livingRoom.appliances.console.status = "off";
        rooms.bedroom.appliances.laptop.status = "off";
        rooms.kitchen.appliances.microwave.status = "off";
        updateApplianceWattages();
        showToast("🔌 Vampire standby power cut. True zero-idle state!");
      }
    });
  }

  // RULE 6: Refrigerator Door Left Ajar
  if (rooms.kitchen.fridgeDoorOpen) {
    reminders.push({
      id: "fridge_door_open",
      severity: "critical",
      title: "Refrigerator Door Left Ajar!",
      desc: `Cold air escaping causes compressor to ramp up from 160W to 320W continuously.`,
      ecoFact: "Leaving a refrigerator door ajar for just 1 minute takes the compressor 10-15 minutes to recover its internal eco-temperature.",
      impact: "Save 160W & protect food freshness",
      actionText: "Close Fridge Door",
      fixAction: () => {
        rooms.kitchen.fridgeDoorOpen = false;
        rooms.kitchen.fridgeDoorSeconds = 0;
        updateApplianceWattages();
        showToast("🧊 Refrigerator door sealed.");
      }
    });
  }

  // RULE 7: Peak Grid Demand Hours Warning
  if (inPeak) {
    const heavyLoads = [];
    if (rooms.bathroom.appliances.geyser.status === "on") heavyLoads.push("Water Geyser (2000W)");
    if (rooms.kitchen.appliances.microwave.status === "on") heavyLoads.push("Microwave (1200W)");
    
    if (heavyLoads.length > 0) {
      reminders.push({
        id: "peak_demand_stress",
        severity: "nudge",
        title: "Peak Grid Stress Hours (6 PM – 10 PM)",
        desc: `High-wattage appliances (${heavyLoads.join(", ")}) running during regional grid peak demand. Thermal peaker plants with higher carbon intensity are running.`,
        ecoFact: "Grid peaker plants emit 25-40% more CO2 per kWh than baseload renewables. Shifting energy use reduces carbon intensity and tariff spikes.",
        impact: "Shift load to off-peak",
        actionText: "Acknowledge Peak",
        fixAction: () => {
          showToast("⏰ Peak awareness noted! Consider postponing heavy cycles.");
        }
      });
    }
  }

  // Play sound if a new critical reminder just popped up
  const previousCriticals = state.activeReminders.filter(r => r.severity === "critical").map(r => r.id);
  const currentCriticals = reminders.filter(r => r.severity === "critical").map(r => r.id);
  const hasNewCritical = currentCriticals.some(id => !previousCriticals.includes(id));

  if (hasNewCritical) {
    playChime("critical");
  } else if (reminders.length > state.activeReminders.length) {
    playChime("nudge");
  }

  state.activeReminders = reminders;
}

// --- Wattage Recalculation ---
function updateApplianceWattages() {
  const rooms = state.rooms;

  // Living Room
  const lr = rooms.livingRoom;
  lr.appliances.fan.watts = lr.appliances.fan.status === "on" ? 75 : 0;
  lr.appliances.lights.watts = lr.appliances.lights.status === "on" ? 30 : 0;
  lr.appliances.tv.watts = lr.appliances.tv.status === "on" ? lr.appliances.tv.activeWatts : (lr.appliances.tv.status === "standby" ? lr.appliances.tv.standbyWatts : 0);
  lr.appliances.console.watts = lr.appliances.console.status === "on" ? lr.appliances.console.activeWatts : (lr.appliances.console.status === "standby" ? lr.appliances.console.standbyWatts : 0);

  // Bedroom
  const br = rooms.bedroom;
  if (br.appliances.ac.status === "on") {
    let baseAcWatts = calculateACWatts(br.acTemp);
    if (br.windowOpen) baseAcWatts += 400; // Extra compressor strain
    br.appliances.ac.watts = baseAcWatts;
  } else {
    br.appliances.ac.watts = 0;
  }
  br.appliances.lights.watts = br.appliances.lights.status === "on" ? 25 : 0;
  br.appliances.laptop.watts = br.appliances.laptop.status === "on" ? br.appliances.laptop.activeWatts : (br.appliances.laptop.status === "standby" ? br.appliances.laptop.standbyWatts : 0);

  // Kitchen
  const kt = rooms.kitchen;
  kt.appliances.fridge.watts = kt.appliances.fridge.status === "on" ? (kt.fridgeDoorOpen ? 320 : 160) : 0;
  kt.appliances.microwave.watts = kt.appliances.microwave.status === "on" ? kt.appliances.microwave.activeWatts : (kt.appliances.microwave.status === "standby" ? kt.appliances.microwave.standbyWatts : 0);
  kt.appliances.exhaust.watts = kt.appliances.exhaust.status === "on" ? 55 : 0;

  // Bathroom
  const bt = rooms.bathroom;
  bt.appliances.geyser.watts = bt.appliances.geyser.status === "on" ? 2000 : 0;
  bt.appliances.exhaust.watts = bt.appliances.exhaust.status === "on" ? 40 : 0;
}

// --- Total Wattage Calculation ---
function getCurrentTotalWatts() {
  let total = 0;
  for (const rKey in state.rooms) {
    const room = state.rooms[rKey];
    for (const aKey in room.appliances) {
      total += room.appliances[aKey].watts || 0;
    }
  }
  return total;
}

// --- Environmental Eco-Score Calculation ---
function computeEcoScore() {
  let score = 100;
  const activeReminders = state.activeReminders;

  // Deduct based on active violations
  activeReminders.forEach(r => {
    if (r.severity === "critical") score -= 15;
    else if (r.severity === "warning") score -= 8;
    else if (r.severity === "nudge") score -= 4;
  });

  const totalWatts = getCurrentTotalWatts();
  if (totalWatts > 2500) score -= 10;
  else if (totalWatts > 1500) score -= 5;

  score = Math.max(35, Math.min(100, score));
  return score;
}

// --- Simulation Step Tick (runs every 1 second) ---
function tickSimulation() {
  if (state.simSpeed === 0) return; // Paused

  // Advance simulation time (1 real second = simSpeed minutes)
  const deltaMinutes = state.simSpeed;
  state.simMinutes += deltaMinutes;

  // Update room vacant / running counters
  for (const rKey in state.rooms) {
    const room = state.rooms[rKey];
    if (!room.occupied) {
      room.vacantMinutes += deltaMinutes;
    } else {
      room.vacantMinutes = 0;
    }
  }

  // Geyser counter
  if (state.rooms.bathroom.appliances.geyser.status === "on") {
    state.rooms.bathroom.geyserMinutes += deltaMinutes;
  } else {
    state.rooms.bathroom.geyserMinutes = 0;
  }

  // Refrigerator door seconds
  if (state.rooms.kitchen.fridgeDoorOpen) {
    state.rooms.kitchen.fridgeDoorSeconds += deltaMinutes * 60;
  } else {
    state.rooms.kitchen.fridgeDoorSeconds = 0;
  }

  // Energy consumption accumulation: kWh = Watts * (hours) / 1000
  const watts = getCurrentTotalWatts();
  const kwhInc = (watts * (deltaMinutes / 60)) / 1000;
  state.totalKwh += kwhInc;

  // Evaluate reminders and wattages
  updateApplianceWattages();
  evaluateRules();
  state.ecoScore = computeEcoScore();

  renderAll();
}

