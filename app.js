// --- Backend Synchronization Service ---
let isBackendConnected = false;

async function checkBackendHealth() {
  try {
    const res = await fetch("/api/status");
    if (res.ok) {
      const data = await res.json();
      isBackendConnected = true;
      const bEl = document.getElementById("backendBadge");
      if (bEl) {
        bEl.textContent = `● Python + SQLite (${data.telemetry_records} logs)`;
        bEl.className = "tariff-tag tariff-normal";
        bEl.style.borderColor = "var(--emerald-500)";
        bEl.style.color = "var(--emerald-400)";
      }
      return true;
    }
  } catch (err) {
    isBackendConnected = false;
    const bEl = document.getElementById("backendBadge");
    if (bEl) {
      bEl.textContent = "○ Standalone Browser Mode";
      bEl.className = "tariff-tag";
      bEl.style.borderColor = "var(--border-color)";
      bEl.style.color = "var(--text-secondary)";
    }
  }
  return false;
}

function syncToBackend(endpoint, payload) {
  if (!isBackendConnected) return;
  fetch(endpoint, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(payload)
  }).catch(() => {});
}

// --- Interactive Control Handlers ---
window.toggleAppliance = function(roomKey, appKey) {
  const app = state.rooms[roomKey].appliances[appKey];
  app.status = app.status === "on" ? "off" : "on";
  syncToBackend("/api/appliance/toggle", { room: roomKey, appliance: appKey });
  updateApplianceWattages();
  evaluateRules();
  renderAll();
};

window.cycleStandby = function(roomKey, appKey) {
  const app = state.rooms[roomKey].appliances[appKey];
  if (app.status === "on") app.status = "standby";
  else if (app.status === "standby") app.status = "off";
  else app.status = "on";
  syncToBackend("/api/appliance/standby", { room: roomKey, appliance: appKey });
  updateApplianceWattages();
  evaluateRules();
  renderAll();
};

window.changeAcTemp = function(newTemp) {
  state.rooms.bedroom.acTemp = parseInt(newTemp, 10);
  syncToBackend("/api/appliance/ac-temp", { temp: state.rooms.bedroom.acTemp });
  updateApplianceWattages();
  evaluateRules();
  renderAll();
};

window.toggleOccupancy = function(roomKey) {
  state.rooms[roomKey].occupied = !state.rooms[roomKey].occupied;
  if (state.rooms[roomKey].occupied) {
    state.rooms[roomKey].vacantMinutes = 0;
  }
  syncToBackend("/api/room/occupancy", { room: roomKey });
  evaluateRules();
  renderAll();
};

window.toggleWindow = function() {
  state.rooms.bedroom.windowOpen = !state.rooms.bedroom.windowOpen;
  syncToBackend("/api/room/window", { windowOpen: state.rooms.bedroom.windowOpen });
  updateApplianceWattages();
  evaluateRules();
  renderAll();
};

window.toggleFridgeDoor = function() {
  state.rooms.kitchen.fridgeDoorOpen = !state.rooms.kitchen.fridgeDoorOpen;
  syncToBackend("/api/room/fridge-door", { open: state.rooms.kitchen.fridgeDoorOpen });
  updateApplianceWattages();
  evaluateRules();
  renderAll();
};

