// --- Navigation Tabs ---
window.switchTab = function(tabId) {
  document.querySelectorAll(".nav-tab").forEach(tab => tab.classList.remove("active"));
  document.querySelectorAll(".tab-panel").forEach(panel => panel.classList.remove("active"));

  const targetTab = document.querySelector(`.nav-tab[data-tab="${tabId}"]`);
  const targetPanel = document.getElementById(tabId);
  if (targetTab) targetTab.classList.add("active");
  if (targetPanel) targetPanel.classList.add("active");
};

// --- Toast Alerts ---
function showToast(msg) {
  const container = document.getElementById("toastContainer");
  if (!container) return;
  const toast = document.createElement("div");
  toast.className = "toast";
  toast.innerHTML = `<span>${msg}</span>`;
  container.appendChild(toast);
  setTimeout(() => {
    toast.style.opacity = "0";
    toast.style.transform = "translateX(100%)";
    toast.style.transition = "all 0.3s ease";
    setTimeout(() => toast.remove(), 300);
  }, 3200);
}

// --- Printable Environmental Audit Modal ---
window.openAuditReport = function() {
  const modal = document.getElementById("auditReportModal");
  const tableBody = document.getElementById("auditTableBody");
  if (!modal || !tableBody) return;

  const totalWatts = getCurrentTotalWatts();
  const dailyKwh = state.totalKwh;
  const monthlyKwh = (dailyKwh * 30).toFixed(1);
  const monthlyCo2 = (monthlyKwh * SIM_CONFIG.emissionFactorKgPerKwh).toFixed(1);

  document.getElementById("auditMonthlyKwh").textContent = monthlyKwh + " kWh";
  document.getElementById("auditMonthlyCo2").textContent = monthlyCo2 + " kg CO₂e";
  document.getElementById("auditScore").textContent = state.ecoScore + "/100 (" + (state.ecoScore >= 80 ? "Grade A" : "Grade B/C") + ")";

  let rows = "";
  for (const rKey in state.rooms) {
    const room = state.rooms[rKey];
    for (const aKey in room.appliances) {
      const app = room.appliances[aKey];
      const dailyAppKwh = ((app.watts * 6) / 1000).toFixed(2); // estimated 6h daily duty cycle
      const monthlyAppCo2 = (dailyAppKwh * 30 * SIM_CONFIG.emissionFactorKgPerKwh).toFixed(1);
      rows += `
        <tr>
          <td><strong>${room.name}</strong> - ${app.name}</td>
          <td>${app.status.toUpperCase()}</td>
          <td>${app.watts} W</td>
          <td>${dailyAppKwh} kWh/day</td>
          <td>${monthlyAppCo2} kg CO₂</td>
        </tr>
      `;
    }
  }
  tableBody.innerHTML = rows;
  syncToBackend("/api/audit/save", {
    monthlyKwh: parseFloat(monthlyKwh),
    monthlyCo2: parseFloat(monthlyCo2),
    score: state.ecoScore,
    grade: state.ecoScore >= 80 ? "Grade A" : "Grade B/C"
  });
  modal.classList.add("open");
};

window.closeAuditReport = function() {
  const modal = document.getElementById("auditReportModal");
  if (modal) modal.classList.remove("open");
};

